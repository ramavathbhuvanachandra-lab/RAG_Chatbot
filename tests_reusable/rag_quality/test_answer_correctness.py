"""
RAG Quality — Answer Correctness Regression Tests.

Failure class: LLM semantic inversion of explicit positive eligibility evidence.

Defects covered
---------------
C2  "Is a first-class qualification accepted for M.Sc. admission?"
    Evidence 1 contains: "OR a first-class as specified by the university/institute"
    Wrong answer: "first-class is NOT explicitly accepted"
    Root cause: qwen2.5:3b misreads multi-clause OR sentence; grounding checker
                has no inversion detector.

C5  "Can a four-year bachelor's degree qualify someone for Ph.D. admission?"
    Evidence 1 contains: "bachelor's degree of minimum four-year duration ... qualifies"
    Wrong answer: "a four-year bachelor's degree alone does not qualify"
    Root cause: same LLM semantic inversion pattern; grounding checker missed it.

Test design principles
----------------------
- UNIT tests use only deterministic fixtures — no LLM, no vector store.
  They can be run in milliseconds.
- INTEGRATION tests (marked @pytest.mark.integration) call the live engine.
  They require Ollama running (qwen2.5:3b) and ChromaDB populated.
- Do NOT use simplistic rules that block every "not" or every "OR" occurrence.
  Faithful paraphrases and genuine negative answers must stay grounded.
- XFAIL tests document contracts not yet satisfied. They flip to PASS when the
  corresponding fix is applied.
- Pre-fix PASS tests document the current broken behaviour (grounding gap).
  Delete them once the corresponding XFAIL contract test turns green.

Relation to existing tests
--------------------------
- tests_reusable/standalone/test_c2_msc_first_class_contract.py holds the
  original 5 C2 contracts. Do not duplicate those tests here; cross-reference.
- tests_reusable/phase3_real_rag/test_answer_grounding.py covers the legacy
  backend module. Tests here target ai_platform.core.answering.grounding.
"""
