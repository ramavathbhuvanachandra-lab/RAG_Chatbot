@pytest.mark.integration
class TestLiveEngineAnswerCorrectness:
    """Live engine must produce affirmative answers for C2 and C5."""

    # FIX VERIFIED 2026-10-13: live engine generates affirmative grounded answer (XPASS verified).
    def test_c2_live_engine_confirms_first_class_accepted(self) -> None:
        """The live engine must not deny that first-class is accepted when
        Evidence 1 explicitly includes 'OR a first-class'.

        Acceptance criteria (after fix):
        - Answer must NOT contain 'not explicitly accepted', 'not mentioned',
          'does not mention first', 'not accepted', 'first-class is not'.
        - Answer must affirmatively confirm that first-class is accepted.
        """
        try:
            from ai_platform.runtime.engine import ask_with_diagnostics
        except ImportError:
            pytest.skip("ai_platform.runtime.engine not importable")

        result = ask_with_diagnostics(
            "Is a first-class qualification accepted for M.Sc. admission?"
        )
        answer = (result.get("answer") or "").lower()

        negative_patterns = [
            r"not explicitly accepted",
            r"not mentioned",
            r"does not mention first",
            r"not accepted",
            r"first-class is not",
            r"first class is not",
            r"\bno\b.*first.class",
        ]
        for pattern in negative_patterns:
            assert not re.search(pattern, answer, re.I), (
                f"C2: Answer contains wrong negative assertion (matched {pattern!r}): "
                f"{answer!r}"
            )

        positive_patterns = [
            r"first.class.*accept",
            r"accept.*first.class",
            r"or.*first.class",
            r"first.class.*qualif",
            r"\byes\b",
        ]
        assert any(re.search(p, answer, re.I) for p in positive_patterns), (
            f"C2: Answer does not affirmatively confirm first-class is accepted: "
            f"{answer!r}"
        )

    # FIX VERIFIED 2026-10-13: live engine generates affirmative grounded answer (XPASS verified).
    def test_c5_live_engine_confirms_four_year_degree_qualifies(self) -> None:
        """The live engine must not deny that a 4-year bachelor's degree qualifies
        for Ph.D. when the top-ranked evidence explicitly lists it as a qualifying path.

        Acceptance criteria (after fix):
        - Answer must NOT contain 'does not qualify', 'alone does not', 'not qualify'.
        - Answer must confirm that a 4-year degree is a qualifying path.
        """
        try:
            from ai_platform.runtime.engine import ask_with_diagnostics
        except ImportError:
            pytest.skip("ai_platform.runtime.engine not importable")

        result = ask_with_diagnostics(
            "Can a four-year bachelor's degree qualify someone for Ph.D. admission?"
        )
        answer = (result.get("answer") or "").lower()

        negative_patterns = [
            r"does not qualify",
            r"alone does not",
            r"not qualify",
            r"four.year.*degree.*not",
            r"\bno\b.*four.year",
        ]
        for pattern in negative_patterns:
            assert not re.search(pattern, answer, re.I), (
                f"C5: Answer contains wrong negative assertion (matched {pattern!r}): "
                f"{answer!r}"
            )

        positive_patterns = [
            r"four.year.*qualif",
            r"qualif.*four.year",
            r"bachelor.*qualif",
            r"\byes\b",
        ]
        assert any(re.search(p, answer, re.I) for p in positive_patterns), (
            f"C5: Answer does not confirm 4-year degree qualifies: {answer!r}"
        )


class TestCategoryThresholdAndPlannerContracts:
    """Unit tests for category threshold fidelity and planner query constraint filtering."""

    def test_category_threshold_misattribution_detected(self):
        from ai_platform.core.answering.grounding import _check_category_threshold_misattribution

        evidence = "minimum of 60% marks for GEN/OBC (55% for SC/ST) category in aggregate"
        wrong_sentence = "For SC and ST candidates, the minimum percentage required is 60% in aggregate."
        issues = _check_category_threshold_misattribution(wrong_sentence, evidence)
        assert len(issues) == 1
        assert issues[0].issue_type == "category_threshold_misattribution"

    def test_category_threshold_correct_attribution_clean(self):
        from ai_platform.core.answering.grounding import _check_category_threshold_misattribution

        evidence = "minimum of 60% marks for GEN/OBC (55% for SC/ST) category in aggregate"
        correct_sentence = "For SC and ST candidates, the minimum percentage required is 55% in aggregate."
        issues = _check_category_threshold_misattribution(correct_sentence, evidence)
        assert len(issues) == 0

    def test_planner_extracts_cutoff_percentage_attribute(self):
        from ai_platform.core.query.planner import _requested_attributes

        query = "I scored 58% in my B.Sc. as an OBC candidate. Do I meet the minimum cut-off percentage for M.Sc.?"
        attrs = _requested_attributes(query)
        assert "minimum percentage" in attrs

    def test_compact_query_omits_candidate_score_from_search(self):
        from ai_platform.core.query.planner import _compact_query

        query = _compact_query("M.Sc", ["minimum percentage"], ["58%", "OBC"])
        assert "58%" not in query
        assert "M.Sc" in query
        assert "OBC" in query
